#!/usr/bin/env python3
"""spec-guard engine — ตรวจ SPEC-POS-001 ด้วย JSON in / JSON out

ทำไมต้องมี: หลักการที่ไม่มีด่าน = คำขวัญ (SPEC §17/§18/§19 ต้องการตัวตรวจ)
ตัวนี้ตรวจ 3 กลุ่มด้วย target เดียว:
  LAYOUT  Y1 backend+frontend · Y2 4 แกน · Y3 .gitignore · Y7 docs+check.py
  SCOPE   B2 generated bytes ≤ 50% · B3 authored÷capability ≤ 3
  ABANDON X1 docs≥10 หรือ span≥3 วัน (day-0 ไม่ตัดสิน) · X2 ถ้าตายแล้วต้องมี ARCHIVE.md

ใช้:
  python scripts/run.py '{"op":"check","target":"C:/path/to/project"}'
  python scripts/run.py '{"op":"layout","target":"."}'
  echo '{"op":"scope","target":"."}' | python scripts/run.py

Deterministic: ไม่มี network, ไม่เขียนไฟล์; "วันนี้" รับได้ผ่าน today เพื่อให้ผลซ้ำได้
"""
from __future__ import annotations

import json
import os
import sys
from datetime import date, datetime
from pathlib import Path

SKIP = {
    "node_modules", ".git", ".venv", ".venv-train", ".uv-cache", "__pycache__", ".svelte-kit",
    ".next", "dist", "build", "coverage", "test-results", "playwright-report", ".pnpm-store", ".tmp",
}
GENERATED = {
    "generated", "out", "site", "experiments", "data/store", "records", "logs", "artifacts",
    "models", "checkpoints", "snapshots",
}
CAP = 5000


def walk(root: Path) -> dict:
    stats = {"files": 0, "bytes": 0, "docs": 0, "mtime_min": None, "mtime_max": None, "gen_bytes": 0}
    for cur, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in SKIP and not d.startswith(".")]
        rel_parts = Path(os.path.relpath(cur, root)).parts
        in_generated = any(part in GENERATED for part in rel_parts)
        for name in filenames:
            if stats["files"] >= CAP:
                return stats
            if name.startswith(".") and name != ".gitignore":
                continue
            full = Path(cur) / name
            try:
                st = full.stat()
            except OSError:
                continue
            stats["files"] += 1
            stats["bytes"] += st.st_size
            if name.lower().endswith(".md"):
                stats["docs"] += 1
            ts = st.st_mtime
            stats["mtime_min"] = ts if stats["mtime_min"] is None else min(stats["mtime_min"], ts)
            stats["mtime_max"] = ts if stats["mtime_max"] is None else max(stats["mtime_max"], ts)
            if in_generated:
                stats["gen_bytes"] += st.st_size
    return stats


def check_layout(root: Path) -> list[dict]:
    rows = []

    def add(cid, label, ok, detail):
        rows.append({"id": cid, "label": label, "ok": bool(ok), "detail": detail})

    backend = (root / "backend").is_dir()
    frontend = (root / "frontend").is_dir()
    root_src = (root / "src").is_dir()
    add("Y1", "backend/ + frontend/ แยกกัน", backend and frontend,
        "มี backend/ แต่ UI อยู่ src/ ที่ root — ต้องย้ายเป็น frontend/"
        if backend and not frontend and root_src else f"backend={backend} frontend={frontend} src(root)={root_src}")

    skills = (root / "skills").is_dir() or (root / "backend" / "skills").is_dir()
    tools = (root / "backend" / "tools").is_dir() or (root / "tools").is_dir()
    knowledge = (root / "data" / "knowledge").is_dir()
    store = (root / "data" / "store").is_dir()
    add("Y2", "4 แกน: skills · tools · data/knowledge · data/store",
        skills and tools and knowledge and store,
        f"skills={skills} tools={tools} knowledge={knowledge} store={store}")

    ignore = ""
    try:
        ignore = (root / ".gitignore").read_text(encoding="utf-8", errors="replace")
    except OSError:
        pass
    found = [x for x in ("data/store", "generated", "node_modules", ".venv") if x in ignore]
    add("Y3", ".gitignore ครอบ store/generated", len(found) >= 4, f"พบ: {', '.join(found) or 'ไม่มี'}")

    docs = (root / "docs").is_dir()
    gate = (root / "backend" / "scripts" / "check.py").exists() or (root / "scripts" / "check.py").exists()
    add("Y7", "มี docs/ + scripts/check.py", docs and gate, f"docs={docs} check={gate}")
    return rows


def check_scope(root: Path, stats: dict) -> list[dict]:
    gen = stats["gen_bytes"]
    authored = max(0, stats["bytes"] - gen)
    ratio = gen / (authored + gen) if authored + gen else 0.0

    tools_dir = root / "backend" / "tools" if (root / "backend" / "tools").is_dir() else root / "tools"
    caps = 0
    if tools_dir.is_dir():
        caps = len([f for f in tools_dir.iterdir() if f.suffix == ".py" and not f.name.startswith("_")])

    rows = [{
        "id": "B2", "label": "generated bytes ≤ 50% ของ repo", "ok": ratio <= 0.5,
        "detail": f"generated={gen // 1024}KB, authored={authored // 1024}KB, ratio={ratio * 100:.0f}%",
    }]
    ok3 = True if caps == 0 else (stats["files"] / caps) <= 3
    rows.append({
        "id": "B3", "label": "authored files ÷ capability ≤ 3", "ok": ok3,
        "detail": f"authored={stats['files']}, capability={caps}, "
                  f"ratio={(stats['files'] / caps):.1f}" if caps else "ไม่พบ tools/ — ข้าม",
    })
    return rows


def check_abandon(root: Path, stats: dict, today: date) -> list[dict]:
    rows = []
    if not stats["mtime_min"]:
        return [{"id": "X1", "label": "มีไฟล์ให้วัด", "ok": False, "detail": "ไม่พบไฟล์"}]
    first = datetime.fromtimestamp(stats["mtime_min"]).date()
    last = datetime.fromtimestamp(stats["mtime_max"]).date()
    span = max(0, (last - first).days)
    idle = max(0, (today - last).days)
    state = "active" if idle <= 3 else ("dormant" if idle <= 14 else "dead")
    fresh = span <= 3 and idle <= 3
    ok = stats["docs"] >= 10 or span >= 3 or fresh
    detail = (f"docs={stats['docs']} span={span}d idle={idle}d — ยังใหม่ (day-0) ยังไม่ตัดสิน"
              if fresh else f"docs={stats['docs']} span={span}d idle={idle}d state={state}")
    rows.append({"id": "X1", "label": "docs ≥ 10 หรือ span ≥ 3 วัน", "ok": ok, "detail": detail})
    if state == "dead":
        rows.append({
            "id": "X2", "label": "ถ้าจะทิ้ง: มีพิธีฝังศพ (B5)",
            "ok": (root / "ARCHIVE.md").exists(),
            "detail": "ไม่พบ ARCHIVE.md — ก่อนเปิดของใหม่ต้องเขียนอะไรมีค่า/อะไรทิ้ง",
        })
    return rows


def parse_request(argv: list[str]) -> tuple[dict | None, str]:
    """รับได้ทั้ง JSON และ shorthand (กันปัญหา PowerShell กิน quote)

    JSON:       run.py '{"op":"check","target":"."}'
    shorthand:  run.py check . --today 2026-10-27
    stdin:      echo ... | run.py
    """
    raw = argv[1] if len(argv) > 1 else (sys.stdin.read() or "{}")
    raw = raw.strip()
    if raw.startswith("{"):
        try:
            return json.loads(raw), ""
        except json.JSONDecodeError as exc:
            return None, f"JSON ไม่ถูกต้อง: {exc}"

    args = argv[1:]
    req: dict[str, str] = {}
    if args and not args[0].startswith("-"):
        req["op"] = args[0]
        args = args[1:]
    for i, token in enumerate(args):
        if token == "--today" and i + 1 < len(args):
            req["today"] = args[i + 1]
        elif not token.startswith("-") and "target" not in req:
            req["target"] = token
    return req, ""


def main(argv: list[str]) -> int:
    req, error = parse_request(argv)
    if error:
        print(json.dumps({"ok": False, "error": error}, ensure_ascii=False))
        return 2
    assert req is not None

    op = str(req.get("op") or "check")
    target = Path(str(req.get("target") or ".")).expanduser().resolve()
    if not target.is_dir():
        print(json.dumps({"ok": False, "error": f"ไม่พบโฟลเดอร์: {target}"}, ensure_ascii=False))
        return 2
    today_raw = req.get("today")
    today = date.fromisoformat(str(today_raw)) if today_raw else date.today()

    stats = walk(target)
    groups = {"layout": check_layout, "scope": lambda r: check_scope(r, stats),
              "abandon": lambda r: check_abandon(r, stats, today)}
    if op not in ("check", *groups):
        print(json.dumps({"ok": False, "error": f"op ไม่รู้จัก: {op}"}, ensure_ascii=False))
        return 2

    checks = []
    if op == "check":
        for fn in (groups["layout"], groups["scope"], groups["abandon"]):
            checks.extend(fn(target))
    else:
        checks.extend(groups[op](target))

    ok = all(c["ok"] for c in checks)
    print(json.dumps({
        "ok": ok, "op": op, "target": str(target),
        "metrics": {"files": stats["files"], "docs": stats["docs"],
                    "authored_kb": max(0, stats["bytes"] - stats["gen_bytes"]) // 1024,
                    "generated_kb": stats["gen_bytes"] // 1024},
        "checks": checks,
    }, ensure_ascii=False, indent=2))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv))
